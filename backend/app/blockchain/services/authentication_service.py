"""
AERO-SHIELD X — Authentication Ledger Service (Module 2)
Python wrapper for the EvidenceVault Authentication Ledger on-chain module.

This service is the primary integration point for Member 1 (Rolling Key
Authentication).  Every authentication event — success or failure — must be
committed here to create an immutable audit trail.

ID conventions in this module
------------------------------
• auth_id, session_id, device_id_bytes — all accepted as hex strings
  ("0x..." or bare hex), converted to bytes32 internally.
• device_id (str) — a human-readable Module 1 string ID such as "UAV-ALPHA-001".
  It is mapped to bytes32 via keccak256 for storage in Module 2.

Caller (Member 1) example:
    svc = AuthenticationService()

    # Record a successful rolling-key authentication
    result = svc.record_authentication(
        auth_id="0xabc123...",       # unique event ID (hex, 32 bytes)
        device_id="UAV-ALPHA-001",   # string ID from Module 1
        key_version=42,              # rolling key generation number
        success=True,                # True = AUTH_SUCCESS, False = AUTH_FAILED
        session_id="0xdef456...",    # session identifier (hex, 32 bytes)
    )
    print(result.tx_hash)

    record = svc.get_authentication("0xabc123...")
    history = svc.get_authentication_history("UAV-ALPHA-001")
"""

from __future__ import annotations

import logging
from dataclasses import dataclass

from ..blockchain_service import BlockchainService, TransactionResult
from ..exceptions import AuthRecordNotFoundError, ContractError
from ..utils import (
    bool_to_auth_status,
    auth_status_to_bool,
    bytes32_to_hex,
    device_id_to_bytes32,
    hex_to_bytes32,
    timestamp_to_iso,
)

logger = logging.getLogger(__name__)


@dataclass
class AuthRecord:
    """Python representation of the on-chain AuthRecord struct."""
    authentication_id: str     # hex string
    device_id_bytes: str       # hex string (keccak256 of original device string ID)
    session_id: str            # hex string
    timestamp: int             # Unix timestamp
    timestamp_iso: str
    rolling_key_version: int
    auth_status: int           # 0 = AUTH_FAILED, 1 = AUTH_SUCCESS
    success: bool              # True if auth_status == 1

    @classmethod
    def from_tuple(cls, t: tuple) -> "AuthRecord":
        """
        Build from the tuple returned by EvidenceVault.getAuthentication().
        Solidity struct field order:
          (authenticationId, deviceId, sessionId, timestamp, rollingKeyVersion,
           authStatus, exists)
        """
        ts = int(t[3])
        return cls(
            authentication_id=bytes32_to_hex(t[0]),
            device_id_bytes=bytes32_to_hex(t[1]),
            session_id=bytes32_to_hex(t[2]),
            timestamp=ts,
            timestamp_iso=timestamp_to_iso(ts),
            rolling_key_version=int(t[4]),
            auth_status=int(t[5]),
            success=auth_status_to_bool(int(t[5])),
        )

    def to_dict(self) -> dict:
        return {
            "authentication_id": self.authentication_id,
            "device_id_bytes": self.device_id_bytes,
            "session_id": self.session_id,
            "timestamp": self.timestamp,
            "timestamp_iso": self.timestamp_iso,
            "rolling_key_version": self.rolling_key_version,
            "auth_status": self.auth_status,
            "success": self.success,
        }


class AuthenticationService:
    """
    Service for Module 2 — Authentication Ledger.

    Device IDs in this module are stored as bytes32 (keccak256 of the Module 1
    string device ID) to keep cross-module lookups deterministic.
    """

    def __init__(self, blockchain_service: BlockchainService | None = None) -> None:
        self._svc = blockchain_service or BlockchainService()

    # ──────────────────────────────────────────────────────────────
    #  Write operations (onlyOwner)
    # ──────────────────────────────────────────────────────────────

    def record_authentication(
        self,
        auth_id: str,
        device_id: str,
        key_version: int,
        success: bool,
        session_id: str,
    ) -> TransactionResult:
        """
        Commit an authentication event to the immutable ledger.

        Args:
            auth_id:     Unique identifier for this authentication event.
                         Provide as a 0x-prefixed hex string (32 bytes / 64 hex chars).
                         Typically generated by Member 1 as: sha256(event_data).hexdigest().
            device_id:   Module 1 string device ID (e.g. "UAV-ALPHA-001").
                         Internally mapped to bytes32 via keccak256.
            key_version: Current rolling key generation number (uint32).
            success:     True → AUTH_SUCCESS (1), False → AUTH_FAILED (0).
            session_id:  Session identifier as a 0x-prefixed hex string (32 bytes).

        Returns:
            TransactionResult

        Raises:
            GasEstimationError: The auth_id already exists on-chain (Solidity require).
            TransactionError:   On-chain execution fails.
        """
        auth_id_bytes = hex_to_bytes32(auth_id)
        device_id_bytes = device_id_to_bytes32(device_id)
        session_id_bytes = hex_to_bytes32(session_id)
        auth_status = bool_to_auth_status(success)

        logger.info(
            "Recording authentication: device=%s key_version=%d success=%s",
            device_id,
            key_version,
            success,
        )

        return self._svc.send_transaction(
            "recordAuthentication",
            auth_id_bytes,
            device_id_bytes,
            int(key_version),
            auth_status,
            session_id_bytes,
        )

    # ──────────────────────────────────────────────────────────────
    #  Read operations (free, no gas)
    # ──────────────────────────────────────────────────────────────

    def get_authentication(self, auth_id: str) -> AuthRecord:
        """
        Retrieve a full AuthRecord by its authentication ID.

        Args:
            auth_id: 0x-prefixed hex string (the same ID used when recording).

        Raises:
            AuthRecordNotFoundError: If no record exists for this ID.
        """
        auth_id_bytes = hex_to_bytes32(auth_id)
        raw = self._svc.call_function("getAuthentication", auth_id_bytes)

        try:
            exists_flag = bool(raw[6])
        except (IndexError, TypeError) as exc:
            raise ContractError(
                f"Unexpected return shape from getAuthentication('{auth_id}'): {raw}",
                details={"raw": str(raw)},
            ) from exc

        if not exists_flag:
            raise AuthRecordNotFoundError(
                f"Authentication record '{auth_id}' not found on-chain.",
                details={"auth_id": auth_id},
            )

        return AuthRecord.from_tuple(raw)

    def get_authentication_history(self, device_id: str) -> list[str]:
        """
        Return all authentication event IDs (as hex strings) for a device.
        Returns an empty list if the device has no recorded events.

        Args:
            device_id: Module 1 string device ID (e.g. "UAV-ALPHA-001").
        """
        device_id_bytes = device_id_to_bytes32(device_id)
        raw = self._svc.call_function("getAuthenticationHistory", device_id_bytes)
        if not raw:
            return []
        return [bytes32_to_hex(entry) for entry in raw]

    def total_authentications(self) -> int:
        """Return the total number of authentication events recorded on-chain."""
        return int(self._svc.call_function("totalAuthentications"))

    def latest_authentication(self) -> AuthRecord | None:
        """
        Return the most recently recorded authentication event, or None if
        no events have been recorded yet.
        """
        if self.total_authentications() == 0:
            return None

        raw = self._svc.call_function("latestAuthentication")
        try:
            exists_flag = bool(raw[6])
        except (IndexError, TypeError):
            return None

        if not exists_flag:
            return None

        return AuthRecord.from_tuple(raw)
